'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const { createFixture, sleep } = require('./collaboration-fixture');
(async () => {
  const fixture = await createFixture({ realGateway: true, startPaused: true });
  const browser = await chromium.launch({ headless: true });
  try {
    const context = await browser.newContext({ extraHTTPHeaders: { 'CF-Access-Jwt-Assertion': fixture.jwt }, viewport: { width: 390, height: 844 } });
    const page = await context.newPage();
    await page.addInitScript(() => {
      window.clipboardReads = 0; window.clipboardFail = false;
      Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { readText: async () => { window.clipboardReads++; if (window.clipboardFail) throw Error('denied'); return 'Clipboard中文\ncontext🙂'; }, writeText: async text => { window.copiedContext = text; } } });
    });
    await page.goto(fixture.url);
    await page.waitForFunction(() => document.querySelector('iframe')?.contentWindow?.webTerminalTarget);
    const button = page.getByRole('button', { name: 'Paste context', exact: true });
    if (!(await button.isVisible())) await page.locator('#toolbar-menu > summary').click();
    await button.click();
    const editor = page.locator('#context-editor'), text = page.locator('#context-text');
    await page.waitForFunction(() => document.querySelector('#context-target').textContent.startsWith('Target:'));
    assert.equal(await page.evaluate(() => window.clipboardReads), 0, 'opening never reads clipboard');
    await page.getByRole('button', { name: 'Read clipboard', exact: true }).click();
    assert.equal(await text.inputValue(), 'Clipboard中文\ncontext🙂');
    assert.equal(await page.getByRole('button', { name: 'Confirm target', exact: true }).isDisabled(), true, 'raw multiline cannot be inserted');
    await page.evaluate(() => { window.clipboardFail = true; });
    await page.getByRole('button', { name: 'Read clipboard', exact: true }).click();
    await page.getByText(/Clipboard permission denied/).waitFor();
    assert.equal(await text.inputValue(), 'Clipboard中文\ncontext🙂', 'denial retains whole draft');
    await text.dispatchEvent('compositionstart');
    await page.keyboard.press('Enter');
    await text.dispatchEvent('compositionend');
    assert.equal(await editor.isVisible(), true, 'IME/editor Enter never sends');
    const draft = await text.inputValue();
    await page.setViewportSize({ width: 844, height: 390 });
    assert.equal(await text.inputValue(), draft, 'rotation retains draft');
    await page.getByRole('button', { name: 'Create context file', exact: true }).click();
    await page.locator('#context-path-label').waitFor({ state: 'visible' });
    const filename = await page.locator('#context-path').inputValue();
    assert.equal(fs.readFileSync(filename, 'utf8'), draft);
    await text.fill('changed after saved file');
    assert.equal(await page.getByRole('button', { name: 'Confirm target', exact: true }).isDisabled(), true, 'edited draft cannot insert an older file');
    await text.fill(draft);
    await page.getByRole('button', { name: 'Copy path', exact: true }).click();
    assert.equal(await page.evaluate(() => window.copiedContext), filename);
    await page.getByRole('button', { name: 'Confirm target', exact: true }).click();
    await page.getByRole('button', { name: 'Insert file path', exact: true }).click();
    await page.getByText(/Inserted once without Enter/).waitFor();
    const snapshot = fixture.tmux('capture-pane', '-p', '-t', 'shared:');
    assert.equal(snapshot.split(filename).length - 1, 1);
    assert.doesNotMatch(snapshot, /Clipboard中文/);
    assert.equal((await fixture.request('GET', '/api/collaboration/state')).data.sessions.shared.paused, true);
    await page.getByRole('button', { name: 'Delete file', exact: true }).click();
    await page.getByText('Context file deleted. Draft retained.', { exact: true }).waitFor();
    assert.equal(fs.existsSync(filename), false);
    await page.getByRole('button', { name: 'Cancel', exact: true }).click();
    await page.waitForFunction(() => document.activeElement === document.querySelector('#paste-context') || document.activeElement === document.querySelector('#toolbar-menu > summary'));
    if (!(await button.isVisible())) await page.locator('#toolbar-menu > summary').click();
    await button.click();
    await page.waitForFunction(() => document.querySelector('#context-target').textContent.startsWith('Target:'));
    assert.equal(await text.inputValue(), draft, 'Cancel/reopen retains draft');
    await text.fill('中'.repeat(22000));
    assert.equal(await page.getByRole('button', { name: 'Create context file', exact: true }).isDisabled(), true);
    await text.fill('SINGLE_LINE_CONTEXT');
    await page.getByRole('button', { name: 'Confirm target', exact: true }).click();
    await text.fill('EDITED_CONTEXT');
    assert.equal(await page.getByRole('button', { name: 'Insert single line', exact: true }).isDisabled(), true, 'edit invalidates confirmation');
    await page.getByRole('button', { name: 'Confirm target', exact: true }).click();
    fixture.tmux('split-window', '-t', 'shared:', '/bin/cat');
    await sleep(500);
    assert.equal(await page.getByRole('button', { name: 'Insert single line', exact: true }).isDisabled(), true, 'native target change invalidates confirmation');
    assert.equal(await text.inputValue(), 'EDITED_CONTEXT');
    await page.getByRole('button', { name: 'Refresh target', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('#context-target').textContent.startsWith('Target:'));
    const dir = path.resolve(process.env.CONTEXT_ARTIFACT_DIR || 'artifacts/context-paste'); fs.mkdirSync(dir, { recursive: true });
    const metrics = [];
    for (const viewport of [{ width: 390, height: 844 }, { width: 1280, height: 800 }, { width: 390, height: 400 }]) {
      await page.setViewportSize(viewport); await sleep(150);
      const result = await page.evaluate(() => { const d = document.querySelector('#context-editor'), buttons = [...d.querySelectorAll('button')].filter(b => !b.hidden); return { width: innerWidth, documentWidth: document.documentElement.scrollWidth, dialogWidth: d.getBoundingClientRect().width, minTouchHeight: Math.min(...buttons.map(b => b.getBoundingClientRect().height)), draft: document.querySelector('textarea#context-text').value }; });
      assert.ok(result.documentWidth <= result.width); assert.ok(result.dialogWidth <= result.width); assert.ok(result.minTouchHeight >= 44); assert.equal(result.draft, 'EDITED_CONTEXT');
      await page.screenshot({ path: path.join(dir, `editor-${viewport.width}x${viewport.height}.png`) }); metrics.push({ viewport, ...result, draft: 'REDACTED_FIXTURE' });
    }
    fs.writeFileSync(path.join(dir, 'metrics.json'), JSON.stringify(metrics, null, 2));
    await context.close();
    console.log(JSON.stringify({ case: 'context-paste-real-signed-owner-browser', clipboardExplicit: 'PASS', deniedNativeFallback: 'PASS', imeEnter: 'PASS', rotateDraft: 'PASS', privateFileAndPath: 'PASS', onceNoEnter: 'PASS', pause: 'PASS', cancelDraft: 'PASS', utf8Limit: 'PASS', targetChange: 'PASS', viewports: 3, physicalIOSAndroid: 'NOT_RUN' }));
  } finally { await browser.close(); await fixture.close(); }
})().catch(error => { console.error(error.stack); process.exitCode = 1; });
